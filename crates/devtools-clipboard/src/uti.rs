//! 剪贴板类型（UTI）常量与内容分析。

use sha2::{Digest, Sha256};

use crate::model::{ContentKind, Snapshot};

/// 文本类的类型。
pub const PLAIN_TEXT: &str = "public.utf8-plain-text";
pub const RTF: &str = "public.rtf";
pub const RTFD: &str = "com.apple.flat-rtfd";
pub const HTML: &str = "public.html";
pub const URL: &str = "public.url";
pub const FILE_URL: &str = "public.file-url";

/// 图片类的类型。
pub const PNG: &str = "public.png";
pub const TIFF: &str = "public.tiff";
pub const JPEG: &str = "public.jpeg";
pub const GIF: &str = "com.compuserve.gif";
pub const BMP: &str = "com.microsoft.bmp";
pub const WEBP: &str = "org.webmproject.webp";
pub const HEIC: &str = "public.heic";

/// 图片类型，顺序即生成缩略图、计算指纹时的优先级。
pub const IMAGE_TYPES: [&str; 7] = [PNG, JPEG, TIFF, GIF, BMP, WEBP, HEIC];

/// nspasteboard.org 约定的标记类型：密码管理器等应用用它们声明“不要记录”。
pub const CONCEALED: &str = "org.nspasteboard.ConcealedType";
/// 临时写入、马上会被还原的内容（例如其他工具借剪贴板传数据）。
pub const TRANSIENT: &str = "org.nspasteboard.TransientType";
/// 程序自动生成、不是用户主动复制的内容。
pub const AUTO_GENERATED: &str = "org.nspasteboard.AutoGeneratedType";
/// 通用剪贴板（Universal Clipboard）从 iPhone/iPad 同步过来的内容。
pub const REMOTE: &str = "com.apple.is-remote-clipboard";

/// 早期应用使用的私有标记，含义与 Concealed / Transient 相同。
pub const LEGACY_CONCEALED: [&str; 2] = ["com.agilebits.onepassword", "com.typeit4me.clipping"];
pub const LEGACY_TRANSIENT: [&str; 2] = [
    "de.petermaurer.TransientPasteboardType",
    "Pasteboard generator type",
];

/// 列表标题最多保留的字符数。
const TITLE_MAX_CHARS: usize = 300;
/// 写入搜索列的文本上限，避免超大文本拖慢 LIKE 查询。
const SEARCH_TEXT_MAX_BYTES: usize = 256 * 1024;

/// 对一次快照的分析结果。
#[derive(Clone, Debug, PartialEq)]
pub struct Analysis {
    pub kind: ContentKind,
    /// 单行预览标题。
    pub title: String,
    /// 全文搜索与预览使用的文本（可能被截断）。
    pub text: String,
    /// 去重指纹：同一内容反复复制时只更新时间和次数。
    pub checksum: String,
    /// 用于生成缩略图的图片类型。
    pub image_uti: Option<&'static str>,
    pub file_paths: Vec<String>,
}

/// 分析快照：判断内容类型，取出标题、搜索文本、文件路径，并计算去重指纹。
pub fn analyze(snapshot: &Snapshot) -> Analysis {
    let plain = plain_text(snapshot);
    let file_paths: Vec<String> = snapshot
        .all(FILE_URL)
        .filter_map(file_url_to_path)
        .collect();
    let image_uti = IMAGE_TYPES
        .iter()
        .copied()
        .find(|uti| snapshot.has_type(uti));
    let has_text = plain.as_deref().is_some_and(|text| !text.trim().is_empty());
    // 微信（4.x 用 Qt 写剪贴板）复制聊天里的图片时，图片数据之外还附带一份临时文件的路径。
    // 只有一个图片文件、又带着图片数据时按图片处理；访达复制文件只附带图标（com.apple.icns），仍是文件。
    let image_file =
        image_uti.is_some() && matches!(file_paths.as_slice(), [path] if is_image_path(path));

    let kind = if image_file {
        ContentKind::Image
    } else if !file_paths.is_empty() {
        ContentKind::Files
    } else if has_text {
        let text = plain.as_deref().unwrap_or_default();
        if is_single_url(text) {
            ContentKind::Link
        } else if snapshot.has_type(RTF) || snapshot.has_type(RTFD) || snapshot.has_type(HTML) {
            ContentKind::RichText
        } else {
            ContentKind::Text
        }
    } else if image_uti.is_some() {
        ContentKind::Image
    } else if plain.is_some() {
        // 只有空白字符的文本，是否记录由规则决定。
        ContentKind::Text
    } else if let Some(url) = snapshot
        .first(URL)
        .and_then(|data| std::str::from_utf8(data).ok())
    {
        // 只有 public.url 没有纯文本的情况（少见），仍按链接处理。
        return finish(
            ContentKind::Link,
            url.trim().to_string(),
            image_uti,
            file_paths,
            snapshot,
        );
    } else {
        ContentKind::Other
    };

    let text = match kind {
        ContentKind::Files => file_paths.join("\n"),
        ContentKind::Image => String::new(),
        ContentKind::Other => snapshot
            .representations()
            .map(|rep| rep.uti.as_str())
            .collect::<Vec<_>>()
            .join(", "),
        _ => plain.unwrap_or_default(),
    };
    finish(kind, text, image_uti, file_paths, snapshot)
}

/// 按类型生成标题与指纹，组装分析结果。
fn finish(
    kind: ContentKind,
    text: String,
    image_uti: Option<&'static str>,
    file_paths: Vec<String>,
    snapshot: &Snapshot,
) -> Analysis {
    let checksum = checksum(kind, &text, image_uti, snapshot);
    let title = match kind {
        ContentKind::Files => {
            let names: Vec<&str> = file_paths
                .iter()
                .map(|path| path.rsplit('/').find(|seg| !seg.is_empty()).unwrap_or(path))
                .collect();
            single_line(&names.join("、"))
        }
        ContentKind::Image => "图片".to_string(),
        _ => single_line(&text),
    };
    Analysis {
        kind,
        title,
        text: truncate_bytes(&text, SEARCH_TEXT_MAX_BYTES).to_string(),
        checksum,
        image_uti: if kind == ContentKind::Image {
            image_uti
        } else {
            None
        },
        file_paths,
    }
}

/// 指纹只取“主要表示”，而不是整份快照：
/// 同一段文字从不同应用复制时附带的 RTF/HTML/来源 URL 各不相同，
/// 但对用户来说是同一条内容（PasteNow 也是对 public 类型数据做 SHA1）。
fn checksum(kind: ContentKind, text: &str, image_uti: Option<&str>, snapshot: &Snapshot) -> String {
    let mut hasher = Sha256::new();
    hasher.update(kind.as_i64().to_le_bytes());
    match kind {
        ContentKind::Image => {
            if let Some(data) = image_uti.and_then(|uti| snapshot.first(uti)) {
                hasher.update(data);
            }
        }
        ContentKind::Other => {
            for rep in snapshot.representations() {
                hasher.update(rep.uti.as_bytes());
                hasher.update((rep.data.len() as u64).to_le_bytes());
                hasher.update(&rep.data);
            }
        }
        _ => hasher.update(text.as_bytes()),
    }
    let digest = hasher.finalize();
    digest[..16]
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect()
}

/// 快照里的纯文本（按 UTF-8 解码，无效字节替换掉）。
pub fn plain_text(snapshot: &Snapshot) -> Option<String> {
    snapshot
        .first(PLAIN_TEXT)
        .map(|data| String::from_utf8_lossy(data).into_owned())
}

/// 是否带有“不要记录”的隐私标记。
pub fn is_concealed(snapshot: &Snapshot) -> bool {
    snapshot.has_type(CONCEALED) || LEGACY_CONCEALED.iter().any(|uti| snapshot.has_type(uti))
}

/// 是否带有“临时内容”标记。
pub fn is_transient(snapshot: &Snapshot) -> bool {
    snapshot.has_type(TRANSIENT) || LEGACY_TRANSIENT.iter().any(|uti| snapshot.has_type(uti))
}

/// 是否带有“自动生成”标记。
pub fn is_auto_generated(snapshot: &Snapshot) -> bool {
    snapshot.has_type(AUTO_GENERATED)
}

/// 是否来自通用剪贴板（iPhone / iPad）。
pub fn is_remote(snapshot: &Snapshot) -> bool {
    snapshot.has_type(REMOTE)
}

/// 路径的扩展名是不是常见的图片格式。
fn is_image_path(path: &str) -> bool {
    const EXTENSIONS: [&str; 10] = [
        "png", "jpg", "jpeg", "gif", "bmp", "tif", "tiff", "webp", "heic", "heif",
    ];
    let name = path.rsplit(['/', '\\']).next().unwrap_or(path);
    name.rsplit_once('.').is_some_and(|(_, extension)| {
        EXTENSIONS
            .iter()
            .any(|image| extension.eq_ignore_ascii_case(image))
    })
}

/// 整段文本是不是一个 http / https 链接（不含空白）。
fn is_single_url(text: &str) -> bool {
    let text = text.trim();
    let lower = text.get(..8).unwrap_or(text).to_ascii_lowercase();
    (lower.starts_with("http://") || lower.starts_with("https://"))
        && text.len() > 8
        && !text.chars().any(char::is_whitespace)
}

/// file URL → 本地路径：
/// - `file:///Users/a/b%20c.txt` → `/Users/a/b c.txt`
/// - `file:///C:/a/b.txt` → `C:\a\b.txt`（Windows 盘符路径）
/// - `file://server/share/x` → `\\server\share\x`（Windows UNC 路径）
pub fn file_url_to_path(data: &[u8]) -> Option<String> {
    let url = std::str::from_utf8(data)
        .ok()?
        .trim_end_matches('\0')
        .trim();
    let rest = url.strip_prefix("file://")?;
    let rest = rest.strip_prefix("localhost").unwrap_or(rest);
    let decoded = percent_decode(rest);
    let path = match decoded.strip_prefix('/') {
        Some(after) if is_drive_path(after) => {
            let windows = after.replace('/', "\\");
            if windows.len() > 3 {
                windows.trim_end_matches('\\').to_string()
            } else {
                windows
            }
        }
        Some(_) if decoded.len() > 1 => decoded.trim_end_matches('/').to_string(),
        Some(_) => decoded,
        None if decoded.is_empty() => decoded,
        None => format!("\\\\{}", decoded.replace('/', "\\").trim_end_matches('\\')),
    };
    (!path.is_empty()).then_some(path)
}

/// 本地路径 → file URL，支持 macOS 路径以及 Windows 的盘符路径和 UNC 路径。
pub fn path_to_file_url(path: &str) -> String {
    if let Some(unc) = path.strip_prefix("\\\\") {
        return format!("file://{}", percent_encode_path(&unc.replace('\\', "/")));
    }
    if is_drive_path(path) {
        return format!("file:///{}", percent_encode_path(&path.replace('\\', "/")));
    }
    format!("file://{}", percent_encode_path(path))
}

/// `C:`、`C:\…`、`C:/…`
fn is_drive_path(path: &str) -> bool {
    let bytes = path.as_bytes();
    bytes.len() >= 2
        && bytes[0].is_ascii_alphabetic()
        && bytes[1] == b':'
        && (bytes.len() == 2 || bytes[2] == b'/' || bytes[2] == b'\\')
}

/// 对路径做百分号编码（保留 `/`、`:` 等路径字符）。
fn percent_encode_path(path: &str) -> String {
    let mut out = String::with_capacity(path.len());
    for byte in path.bytes() {
        match byte {
            b'A'..=b'Z' | b'a'..=b'z' | b'0'..=b'9' | b'/' | b'-' | b'_' | b'.' | b'~' | b':' => {
                out.push(byte as char)
            }
            _ => out.push_str(&format!("%{byte:02X}")),
        }
    }
    out
}

/// 百分号解码；不完整或无效的 `%xx` 原样保留。
fn percent_decode(input: &str) -> String {
    let bytes = input.as_bytes();
    let mut out = Vec::with_capacity(bytes.len());
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'%' && i + 2 < bytes.len() {
            let hex = std::str::from_utf8(&bytes[i + 1..i + 3]).ok();
            if let Some(value) = hex.and_then(|h| u8::from_str_radix(h, 16).ok()) {
                out.push(value);
                i += 3;
                continue;
            }
        }
        out.push(bytes[i]);
        i += 1;
    }
    String::from_utf8_lossy(&out).into_owned()
}

/// 把多行文本压成一行，用于列表标题。
pub fn single_line(text: &str) -> String {
    let mut out = String::new();
    let mut count = 0;
    let mut pending_space = false;
    for ch in text.chars() {
        if ch.is_whitespace() {
            pending_space = !out.is_empty();
            continue;
        }
        if pending_space {
            out.push(' ');
            count += 1;
            pending_space = false;
        }
        if count >= TITLE_MAX_CHARS {
            out.push('…');
            break;
        }
        out.push(ch);
        count += 1;
    }
    out
}

/// 截取不超过 `max` 字节的前缀（不截断多字节字符）。
pub fn truncate_bytes(text: &str, max: usize) -> &str {
    if text.len() <= max {
        return text;
    }
    let mut end = max;
    while !text.is_char_boundary(end) {
        end -= 1;
    }
    &text[..end]
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::Representation;

    fn snap(reps: &[(&str, &[u8])]) -> Snapshot {
        Snapshot {
            items: vec![reps
                .iter()
                .map(|(uti, data)| Representation::new(*uti, *data))
                .collect()],
        }
    }

    #[test]
    fn plain_text_is_text() {
        let analysis = analyze(&Snapshot::from_text("  hello\n  world  "));
        assert_eq!(analysis.kind, ContentKind::Text);
        assert_eq!(analysis.title, "hello world");
        assert_eq!(analysis.text, "  hello\n  world  ");
    }

    #[test]
    fn text_with_rtf_is_rich_text() {
        let analysis = analyze(&snap(&[(PLAIN_TEXT, b"hi"), (RTF, b"{\\rtf1 hi}")]));
        assert_eq!(analysis.kind, ContentKind::RichText);
    }

    #[test]
    fn single_url_is_link() {
        let analysis = analyze(&Snapshot::from_text("https://example.com/a?b=1"));
        assert_eq!(analysis.kind, ContentKind::Link);
        let analysis = analyze(&Snapshot::from_text("see https://example.com"));
        assert_eq!(analysis.kind, ContentKind::Text);
    }

    #[test]
    fn files_take_priority_and_decode_paths() {
        let snapshot = Snapshot {
            items: vec![
                vec![
                    Representation::new(FILE_URL, b"file:///Users/me/a%20b.txt".to_vec()),
                    Representation::new(PLAIN_TEXT, b"a b.txt".to_vec()),
                ],
                vec![Representation::new(
                    FILE_URL,
                    b"file:///Users/me/dir/".to_vec(),
                )],
            ],
        };
        let analysis = analyze(&snapshot);
        assert_eq!(analysis.kind, ContentKind::Files);
        assert_eq!(
            analysis.file_paths,
            vec!["/Users/me/a b.txt", "/Users/me/dir"]
        );
        assert_eq!(analysis.title, "a b.txt、dir");
    }

    #[test]
    fn image_without_text_is_image() {
        let analysis = analyze(&snap(&[(TIFF, b"II*\0"), (PNG, b"\x89PNG")]));
        assert_eq!(analysis.kind, ContentKind::Image);
        assert_eq!(analysis.image_uti, Some(PNG));
    }

    #[test]
    fn copied_chat_image_with_temp_file_is_image() {
        // 微信复制聊天图片：临时文件的路径 + TIFF 图片数据 + Qt 的标记类型。
        let url: &[u8] = b"file://localhost/Users/me/Library/Containers/com.tencent.xinWeChat/temp/RWTemp/4801da0c.png";
        let wechat = snap(&[
            (FILE_URL, url),
            ("com.trolltech.anymime.text--uri-list", b""),
            (TIFF, b"MM\0*"),
            ("com.trolltech.anymime.application--x-qt-image", b""),
        ]);
        let analysis = analyze(&wechat);
        assert_eq!(analysis.kind, ContentKind::Image);
        assert_eq!(analysis.image_uti, Some(TIFF));
        assert_eq!(analysis.title, "图片");
        // 路径仍然保留：纯文本粘贴、选中内容面板还能用到。
        assert_eq!(analysis.file_paths.len(), 1);
        // 同一张图换了临时文件名，仍是同一条记录。
        let renamed = snap(&[
            (FILE_URL, b"file:///Users/me/temp/other.png"),
            (TIFF, b"MM\0*"),
        ]);
        assert_eq!(analyze(&renamed).checksum, analysis.checksum);

        // 访达复制图片文件：只附带图标，仍是文件。
        let finder = snap(&[
            (FILE_URL, b"file:///Users/me/a.png"),
            (PLAIN_TEXT, b"a.png"),
            ("com.apple.icns", b"icns"),
        ]);
        assert_eq!(analyze(&finder).kind, ContentKind::Files);
        // 不是图片的文件、多个文件，即使带着图片数据也仍是文件。
        let document = snap(&[(FILE_URL, b"file:///Users/me/a.pdf"), (TIFF, b"MM\0*")]);
        assert_eq!(analyze(&document).kind, ContentKind::Files);
        let several = Snapshot {
            items: vec![
                vec![
                    Representation::new(FILE_URL, b"file:///Users/me/a.png".to_vec()),
                    Representation::new(TIFF, b"MM\0*".to_vec()),
                ],
                vec![Representation::new(
                    FILE_URL,
                    b"file:///Users/me/b.png".to_vec(),
                )],
            ],
        };
        assert_eq!(analyze(&several).kind, ContentKind::Files);
    }

    #[test]
    fn recognizes_image_paths() {
        assert!(is_image_path("/Users/me/a.PNG"));
        assert!(is_image_path(r"C:\Users\me\photo.jpeg"));
        assert!(!is_image_path("/Users/me/a.png.txt"));
        assert!(!is_image_path("/Users/me/png"));
        assert!(!is_image_path("/Users/me.png/readme"));
    }

    #[test]
    fn excel_like_content_with_text_and_image_is_text() {
        let analysis = analyze(&snap(&[
            (PLAIN_TEXT, b"a\tb"),
            (HTML, b"<table/>"),
            (PNG, b"x"),
        ]));
        assert_eq!(analysis.kind, ContentKind::RichText);
        assert_eq!(analysis.image_uti, None);
    }

    #[test]
    fn checksum_ignores_formatting_but_not_content() {
        let a = analyze(&snap(&[(PLAIN_TEXT, b"same"), (HTML, b"<b>same</b>")]));
        let b = analyze(&snap(&[(PLAIN_TEXT, b"same"), (RTF, b"{\\rtf1 same}")]));
        let c = analyze(&snap(&[(PLAIN_TEXT, b"other"), (RTF, b"{\\rtf1 same}")]));
        assert_eq!(a.checksum, b.checksum);
        assert_ne!(a.checksum, c.checksum);
        assert_eq!(a.checksum.len(), 32);
    }

    #[test]
    fn markers_are_detected() {
        assert!(is_concealed(&snap(&[
            (PLAIN_TEXT, b"pw"),
            (CONCEALED, b"")
        ])));
        assert!(is_concealed(&snap(&[
            (PLAIN_TEXT, b"pw"),
            ("com.agilebits.onepassword", b"")
        ])));
        assert!(is_transient(&snap(&[(TRANSIENT, b"")])));
        assert!(is_auto_generated(&snap(&[(AUTO_GENERATED, b"")])));
        assert!(is_remote(&snap(&[(REMOTE, b"")])));
    }

    #[test]
    fn file_url_round_trip() {
        let path = "/Users/me/文档/a b#1.txt";
        let url = path_to_file_url(path);
        assert_eq!(file_url_to_path(url.as_bytes()).as_deref(), Some(path));
    }

    #[test]
    fn windows_paths_round_trip() {
        for (path, expected_url) in [
            (
                r"C:\Users\我\a b.txt",
                "file:///C:/Users/%E6%88%91/a%20b.txt",
            ),
            (r"D:\", "file:///D:/"),
            (r"\\server\share\x.zip", "file://server/share/x.zip"),
        ] {
            let url = path_to_file_url(path);
            assert_eq!(url, expected_url);
            assert_eq!(file_url_to_path(url.as_bytes()).as_deref(), Some(path));
        }
        // 其他程序常见的写法也能识别。
        assert_eq!(
            file_url_to_path(b"file:///c:/tmp/").as_deref(),
            Some(r"c:\tmp")
        );
        assert_eq!(
            file_url_to_path(b"file://localhost/C:/x").as_deref(),
            Some(r"C:\x")
        );
    }

    #[test]
    fn single_line_truncates() {
        let long = "字".repeat(400);
        let title = single_line(&long);
        assert_eq!(title.chars().count(), TITLE_MAX_CHARS + 1);
        assert!(title.ends_with('…'));
    }
}
