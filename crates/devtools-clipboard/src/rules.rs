//! 记录过滤规则（对应 PasteNow 的 “Exclusion Rules”）。

use serde::{Deserialize, Serialize};

use crate::model::{ContentKind, Snapshot, SourceApp};
use crate::uti::{self, Analysis};

/// 排除的应用。macOS 上 `bundle_id` 是 Bundle ID；Windows 上是程序路径或文件名（如 `KeePass.exe`）。
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct ExcludedApp {
    pub bundle_id: String,
    #[serde(default)]
    pub name: String,
}

impl ExcludedApp {
    /// 不区分大小写；Windows 上只写文件名时，匹配任意目录下的同名程序。
    pub fn matches(&self, source_id: &str) -> bool {
        source_id.eq_ignore_ascii_case(&self.bundle_id)
            || source_id
                .rsplit(['\\', '/'])
                .next()
                .is_some_and(|file_name| file_name.eq_ignore_ascii_case(&self.bundle_id))
    }
}

/// 记录剪贴板时的过滤规则（设置页“隐私与排除规则”）。
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(default)]
pub struct CaptureRules {
    /// 忽略标记为 Concealed 的内容（密码管理器复制的密码）。
    pub ignore_concealed: bool,
    /// 忽略标记为 Transient 的内容（其他工具临时写入、马上会还原的数据）。
    pub ignore_transient: bool,
    /// 忽略标记为 AutoGenerated 的内容。
    pub ignore_auto_generated: bool,
    /// 忽略通过“通用剪贴板”从 iPhone/iPad 同步来的内容。
    pub ignore_remote: bool,
    /// 忽略只有空白字符的文本。
    pub ignore_blank_text: bool,
    /// 超过该大小（MB）的内容不记录，0 表示不限制。
    pub max_size_mb: u32,
    /// 来自这些应用的复制不记录。
    pub excluded_apps: Vec<ExcludedApp>,
}

impl Default for CaptureRules {
    fn default() -> Self {
        let app = |bundle_id: &str, name: &str| ExcludedApp {
            bundle_id: bundle_id.to_string(),
            name: name.to_string(),
        };
        Self {
            ignore_concealed: true,
            ignore_transient: true,
            ignore_auto_generated: true,
            ignore_remote: false,
            ignore_blank_text: true,
            max_size_mb: 64,
            #[cfg(not(windows))]
            excluded_apps: vec![
                app("com.apple.keychainaccess", "钥匙串访问"),
                app("com.apple.Passwords", "密码"),
                app("com.1password.1password", "1Password"),
                app("com.bitwarden.desktop", "Bitwarden"),
            ],
            #[cfg(windows)]
            excluded_apps: vec![
                app("KeePass.exe", "KeePass"),
                app("KeePassXC.exe", "KeePassXC"),
                app("1Password.exe", "1Password"),
                app("Bitwarden.exe", "Bitwarden"),
            ],
        }
    }
}

/// 某次复制没有被记录的原因（写进调试日志）。
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum SkipReason {
    Empty,
    Concealed,
    Transient,
    AutoGenerated,
    Remote,
    Blank,
    TooLarge { bytes: usize, limit: usize },
    ExcludedApp(String),
}

impl std::fmt::Display for SkipReason {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            SkipReason::Empty => write!(f, "剪贴板为空"),
            SkipReason::Concealed => write!(f, "内容被标记为 Concealed"),
            SkipReason::Transient => write!(f, "内容被标记为 Transient"),
            SkipReason::AutoGenerated => write!(f, "内容被标记为 AutoGenerated"),
            SkipReason::Remote => write!(f, "来自通用剪贴板"),
            SkipReason::Blank => write!(f, "只包含空白字符"),
            SkipReason::TooLarge { bytes, limit } => write!(f, "大小 {bytes} 超过上限 {limit}"),
            SkipReason::ExcludedApp(id) => write!(f, "来源应用 {id} 在排除列表中"),
        }
    }
}

impl CaptureRules {
    /// 在读取完整数据之前就能判断的规则（标记类型、来源应用）。
    pub fn check_markers(&self, types: &[String], source: &SourceApp) -> Result<(), SkipReason> {
        let has = |uti: &str| types.iter().any(|t| t == uti);
        if types.is_empty() {
            return Err(SkipReason::Empty);
        }
        if self.ignore_concealed
            && (has(uti::CONCEALED) || uti::LEGACY_CONCEALED.iter().any(|t| has(t)))
        {
            return Err(SkipReason::Concealed);
        }
        if self.ignore_transient
            && (has(uti::TRANSIENT) || uti::LEGACY_TRANSIENT.iter().any(|t| has(t)))
        {
            return Err(SkipReason::Transient);
        }
        if self.ignore_auto_generated && has(uti::AUTO_GENERATED) {
            return Err(SkipReason::AutoGenerated);
        }
        if self.ignore_remote && has(uti::REMOTE) {
            return Err(SkipReason::Remote);
        }
        if let Some(bundle_id) = source.bundle_id.as_deref() {
            if self.excluded_apps.iter().any(|app| app.matches(bundle_id)) {
                return Err(SkipReason::ExcludedApp(bundle_id.to_string()));
            }
        }
        Ok(())
    }

    /// 完整检查：标记、大小、空白内容。
    pub fn check(
        &self,
        snapshot: &Snapshot,
        analysis: &Analysis,
        source: &SourceApp,
    ) -> Result<(), SkipReason> {
        if snapshot.is_empty() {
            return Err(SkipReason::Empty);
        }
        let types: Vec<String> = snapshot
            .representations()
            .map(|rep| rep.uti.clone())
            .collect();
        self.check_markers(&types, source)?;
        if self.max_size_mb > 0 {
            let limit = self.max_size_mb as usize * 1024 * 1024;
            let bytes = snapshot.total_bytes();
            if bytes > limit {
                return Err(SkipReason::TooLarge { bytes, limit });
            }
        }
        if self.ignore_blank_text
            && (analysis.kind.is_textual() || analysis.kind == ContentKind::Link)
            && analysis.text.trim().is_empty()
        {
            return Err(SkipReason::Blank);
        }
        if analysis.kind == ContentKind::Other && snapshot.total_bytes() == 0 {
            return Err(SkipReason::Empty);
        }
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::Representation;
    use crate::uti::analyze;

    fn check(
        rules: &CaptureRules,
        snapshot: &Snapshot,
        bundle: Option<&str>,
    ) -> Result<(), SkipReason> {
        let source = SourceApp {
            bundle_id: bundle.map(str::to_string),
            name: None,
        };
        rules.check(snapshot, &analyze(snapshot), &source)
    }

    #[test]
    fn accepts_normal_text() {
        assert_eq!(
            check(&CaptureRules::default(), &Snapshot::from_text("hi"), None),
            Ok(())
        );
    }

    #[test]
    fn rejects_concealed_and_can_be_disabled() {
        let mut snapshot = Snapshot::from_text("secret");
        snapshot.items[0].push(Representation::new(uti::CONCEALED, Vec::new()));
        let mut rules = CaptureRules::default();
        assert_eq!(check(&rules, &snapshot, None), Err(SkipReason::Concealed));
        rules.ignore_concealed = false;
        assert_eq!(check(&rules, &snapshot, None), Ok(()));
    }

    #[test]
    fn rejects_excluded_app() {
        let rules = CaptureRules {
            excluded_apps: vec![ExcludedApp {
                bundle_id: "com.1password.1password".into(),
                name: String::new(),
            }],
            ..CaptureRules::default()
        };
        assert!(matches!(
            check(
                &rules,
                &Snapshot::from_text("x"),
                Some("com.1password.1password")
            ),
            Err(SkipReason::ExcludedApp(_))
        ));
    }

    #[test]
    fn excluded_app_matches_windows_file_names() {
        let app = ExcludedApp {
            bundle_id: "KeePass.exe".into(),
            name: String::new(),
        };
        assert!(app.matches(r"C:\Program Files\KeePass Password Safe 2\KeePass.exe"));
        assert!(app.matches("keepass.exe"));
        assert!(!app.matches(r"C:\Tools\NotKeePass.exe"));
        let mac = ExcludedApp {
            bundle_id: "com.apple.Passwords".into(),
            name: String::new(),
        };
        assert!(mac.matches("com.apple.Passwords"));
        assert!(!mac.matches("com.apple.PasswordsHelper"));
    }

    #[test]
    fn rejects_blank_and_large() {
        let mut rules = CaptureRules::default();
        assert_eq!(
            check(&rules, &Snapshot::from_text(" \n\t"), None),
            Err(SkipReason::Blank)
        );
        rules.max_size_mb = 1;
        let big = "a".repeat(1024 * 1024 + 1);
        assert!(matches!(
            check(&rules, &Snapshot::from_text(&big), None),
            Err(SkipReason::TooLarge { .. })
        ));
        rules.max_size_mb = 0;
        assert_eq!(check(&rules, &Snapshot::from_text(&big), None), Ok(()));
    }

    #[test]
    fn rejects_empty() {
        assert_eq!(
            check(&CaptureRules::default(), &Snapshot::default(), None),
            Err(SkipReason::Empty)
        );
    }
}
